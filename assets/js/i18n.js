  var dicts = { en: en, zh: zh, es: es, fr: fr, ru: ru };

  function apply(code) {
    var dict = dicts[code] || en;
    document.documentElement.lang = code === "zh" ? "zh-CN" : code;

    var nodes = document.querySelectorAll("[data-i18n]");
    Array.prototype.forEach.call(nodes, function (el) {
      var key = el.getAttribute("data-i18n");
      var value = dict[key] || en[key];
      if (typeof value === "string") el.innerHTML = value;
    });

    var ph = document.querySelectorAll("[data-i18n-placeholder]");
    Array.prototype.forEach.call(ph, function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      el.setAttribute("placeholder", dict[key] || en[key] || "");
    });

    var aria = document.querySelectorAll("[data-i18n-aria]");
    Array.prototype.forEach.call(aria, function (el) {
      var key = el.getAttribute("data-i18n-aria");
      el.setAttribute("aria-label", dict[key] || en[key] || "");
    });
  }

  window.SARGARA_I18N = { apply: apply, dicts: dicts };
